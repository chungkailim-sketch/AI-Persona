// @vitest-environment node
/** The AIGC creative brief: preferences saved, brief written (mock model), Word template filled. */
process.env.DATABASE_URL =
  process.env.DATABASE_URL_TEST ?? 'postgresql://postgres@localhost:55432/rfpi_test?host=/tmp';
process.env.SESSION_SECRET = 'test-session-secret-at-least-32-characters-long';
process.env.IP_HASH_PEPPER = 'test-pepper';
process.env.MODEL_PROVIDER = 'mock';

import { describe, it, expect, beforeEach, afterAll } from 'vitest';
import { randomUUID } from 'node:crypto';
import JSZip from 'jszip';
import { db, resetDatabase, seedUser } from './helpers';
import type { SessionUser } from '../../src/auth/session';
import { createProject } from '../../src/server/projects';
import { setModelProvider } from '../../src/model/client';
import { MockProvider } from '../../src/model/mock';
import { saveStudyBrief, JourneyRefused } from '../../src/roundtable/service';
import { executeCreativeBrief, requestCreativeBrief } from '../../src/creative/brief';
import { creativeBriefDocx } from '../../src/creative/docx';
import type { CreativeBriefContent } from '../../src/creative/fields';

setModelProvider(new MockProvider());
const asSession = (u: { id: string; email: string; systemRole: string }): SessionUser => ({
  userId: u.id, email: u.email, displayName: 'Mei Tan', systemRole: u.systemRole as SessionUser['systemRole'], sessionId: 'test',
});

describe('creative brief', () => {
  beforeEach(async () => { await resetDatabase(); });
  afterAll(async () => { await db.$disconnect(); });

  it('writes the brief from the study alone and fills the Word template', async () => {
    const owner = asSession(await seedUser(`cb-${randomUUID().slice(0, 8)}@example.com`));
    const { id: projectId } = await createProject(owner, { name: 'CBGA Outlook 2027' });
    await expect(requestCreativeBrief(owner, projectId)).rejects.toBeInstanceOf(JourneyRefused);

    await saveStudyBrief(owner, projectId, { context: 'A Shenzhen skincare brand.', markets: ['Indonesia'], question: 'Which categories would you try a Chinese brand in?', categories: ['Beauty', 'Food'], audience: 'Young urban adults' });

    // Nothing is typed in for the creative brief: it is written from the study.
    const { adviceId } = await requestCreativeBrief(owner, projectId);
    expect((await executeCreativeBrief(adviceId)).status).toBe('COMPLETED');
    const advice = await db.advice.findUniqueOrThrow({ where: { id: adviceId } });
    const content = advice.content as unknown as CreativeBriefContent;
    expect(content.fields).toMatchObject({ projectTitle: 'CBGA Outlook 2027', owner: 'Mei Tan', version: 'v1' });
    expect(content.fields.concept).toContain('[MOCK]');
    // A row the model left empty is still filled, and flagged as inferred.
    expect(content.fields.lens).toBe('50mm, shallow depth of field');
    expect(content.basis.at(-1)).toMatch(/^Inferred where the study is silent.*Platform \/ placement.*Total runtime.*Lens \/ depth of field/);
    // Every row of the template has a value.
    expect(Object.values(content.fields).every((v) => v.trim().length > 0)).toBe(true);
    expect(content.shots.length).toBeGreaterThan(0);

    const docx = await creativeBriefDocx(content, { projectName: 'CBGA Outlook 2027', generatedOn: '2026-11-12' });
    const xml = await (await JSZip.loadAsync(docx)).file('word/document.xml')!.async('string');
    const text = [...xml.matchAll(/<w:t[^>]*>([^<]*)<\/w:t>/g)].map((m) => m[1]).join('');
    expect(text).toContain('AIGC Creative Brief — CBGA Outlook 2027');
    expect(text).toContain('Generated by RF AI Persona on 2026-11-12');
    expect(xml).toContain('Shot 1');
    expect(xml).toContain('Insight basis (RF AI Persona)');
    // Every template row keeps its Field and Guidance text.
    expect(xml).toContain('Short name, reused in file names and version labels');
    expect(xml.match(/<w:tbl>/g)?.length).toBe(7);
  });
});
