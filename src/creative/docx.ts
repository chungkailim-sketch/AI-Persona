/**
 * Fill the AI-Persona-to-AIGC Creative Brief Template (.docx) with a generated brief (server only).
 *
 * The supplied template is kept as it is — its title, sections, tables, Field and Guidance columns
 * and styles — and only the "Your input" column is written, row by row, found by each row's Field
 * label. The input column is widened so the content reads (the template's narrow column was for
 * handwriting-length notes); the three columns still span the page.
 */
import JSZip from 'jszip';
import { TEMPLATE_DOCX_BASE64 } from './template';
import { BRIEF_FIELDS, SHOTS_LABEL, type CreativeBriefContent } from './fields';

// Field · Your input · Guidance, in twentieths of a point (sums to the template's 6.5 in text width).
const WIDTHS = [2000, 4560, 2800];

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const plain = (xml: string) => [...xml.matchAll(/<w:t[^>]*>([^<]*)<\/w:t>/g)].map((m) => m[1]).join('').trim();

function paragraphs(lines: string[], bold = false): string {
  const rPr = bold ? '<w:rPr><w:b/></w:rPr>' : '';
  return (lines.length ? lines : ['']).map((l) => `<w:p><w:r>${rPr}<w:t xml:space="preserve">${esc(l)}</w:t></w:r></w:p>`).join('');
}

/** One cell's content replaced, its properties (width, shading) kept. */
function fillCell(cell: string, body: string): string {
  const pr = /<w:tcPr>[\s\S]*?<\/w:tcPr>/.exec(cell)?.[0] ?? '';
  return `<w:tc>${pr}${body}</w:tc>`;
}

function widen(table: string): string {
  let col = 0;
  let out = table.replace(/<w:gridCol w:w="\d+"\/>/g, () => `<w:gridCol w:w="${WIDTHS[col++ % 3]}"/>`);
  out = out.replace(/<w:tr\b[\s\S]*?<\/w:tr>/g, (row) => {
    let c = 0;
    return row.replace(/<w:tcW w:w="\d+" w:type="dxa"\/>/g, () => `<w:tcW w:w="${WIDTHS[c++ % 3]}" w:type="dxa"/>`);
  });
  return out;
}

export interface DocxMeta { projectName: string; generatedOn: string }

export async function creativeBriefDocx(content: CreativeBriefContent, meta: DocxMeta): Promise<Buffer> {
  const zip = await JSZip.loadAsync(Buffer.from(TEMPLATE_DOCX_BASE64, 'base64'));
  let xml = await zip.file('word/document.xml')!.async('string');
  const byLabel = new Map(BRIEF_FIELDS.map((f) => [f.label, content.fields[f.key] ?? '']));

  xml = xml.replace(/<w:tbl>[\s\S]*?<\/w:tbl>/g, (table) =>
    widen(table).replace(/<w:tr\b[\s\S]*?<\/w:tr>/g, (row) => {
      const cells = row.match(/<w:tc>[\s\S]*?<\/w:tc>/g);
      if (!cells || cells.length < 3) return row;
      const label = plain(cells[0]!);
      let body: string | null = null;
      if (label === SHOTS_LABEL) {
        body = content.shots.length
          ? content.shots.map((s, i) => paragraphs([`Shot ${i + 1}${s.title ? ` — ${s.title}` : ''}`], true) + paragraphs([s.prompt])).join('')
          : paragraphs(['']);
      } else if (byLabel.has(label)) {
        body = paragraphs((byLabel.get(label) ?? '').split('\n').map((l) => l.trim()).filter(Boolean));
      }
      return body === null ? row : row.replace(cells[1]!, fillCell(cells[1]!, body));
    }),
  );

  // Title and the opening instruction now describe this filled brief.
  // The template's title is two runs: "AIGC" + " Creative Brief Template".
  xml = xml.replace('> Creative Brief Template<', `>${esc(` Creative Brief — ${meta.projectName}`)}<`);
  xml = xml.replace(
    /(<w:t[^>]*>)Fill every row in the Your input column before generating;[^<]*(<\/w:t>)/,
    `$1${esc(
      `Generated by RF AI Persona on ${meta.generatedOn} from the study brief, the communication preferences and creative treatment, and the key messaging of the simulated consumer roundtable. ` +
        'Review every row before generating; each field removes a decision Runway would otherwise guess. Audience insight comes from simulated personas built on published survey data: treat it as a hypothesis.',
    )}$2`,
  );
  // Evidence the brief rests on, in the empty heading left at the end of the template.
  if (content.basis.length) {
    const tail = /<w:p [^>]*><w:pPr><w:pStyle w:val="Heading2"\/><\/w:pPr><\/w:p>(?=<w:sectPr)/;
    xml = xml.replace(tail, `<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr><w:r><w:t>Insight basis (RF AI Persona)</w:t></w:r></w:p>${content.basis.map((b) => `<w:p><w:pPr><w:pStyle w:val="ListParagraph"/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="1"/></w:numPr></w:pPr><w:r><w:t xml:space="preserve">${esc(b)}</w:t></w:r></w:p>`).join('')}`);
  }
  zip.file('word/document.xml', xml);
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}
