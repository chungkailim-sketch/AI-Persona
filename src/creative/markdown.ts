/**
 * The AIGC creative brief as Markdown, in the order and wording of the Word template: one table per
 * section (Field · Your input), the shot prompts, and the insight basis. For pasting into an AIGC
 * tool, a prompt library or a document.
 */
import { BRIEF_FIELDS, type CreativeBriefContent } from './fields';

export const SECTION_TITLES: Record<string, string> = {
  '1': '1. Project basics',
  '2': '2. Objective and output specs',
  '3': '3. Concept and creative direction',
  '4': '4. Subject and scene',
  '5': '5. Camera and motion',
  '6': '6. Visual style and look',
  '9': '9. Final prompt assembly',
};

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, '<br>').trim() || '—';

export function creativeBriefMarkdown(content: CreativeBriefContent, meta: { projectName: string; generatedOn: string }): string {
  const out: string[] = [
    `# AIGC Creative Brief — ${meta.projectName}`,
    '',
    `_Generated by RF AI Persona on ${meta.generatedOn} from the study: the personas, the roundtable results and key messaging, the report's market indices, the latest plan and debate. Review every row before generating. Audience insight comes from simulated personas built on published survey data: treat it as a hypothesis._`,
  ];
  for (const [section, title] of Object.entries(SECTION_TITLES)) {
    out.push('', `## ${title}`, '');
    if (section === '9') {
      out.push('Each shot prompt: [Shot type + camera movement]: [Subject with consistency anchors] [action] in [environment], [time of day]. [Lighting]. [Style, film look, palette].', '');
      out.push('### Master prompt (per shot)', '');
      content.shots.forEach((s, i) => out.push(`**Shot ${i + 1}${s.title ? ` — ${s.title}` : ''}**`, '', '```', s.prompt, '```', ''));
    }
    out.push('| Field | Your input |', '|---|---|');
    for (const f of BRIEF_FIELDS.filter((x) => x.section === section)) out.push(`| ${f.label} | ${cell(content.fields[f.key] ?? '')} |`);
  }
  if (content.basis.length) out.push('', '## Insight basis (RF AI Persona)', '', ...content.basis.map((b) => `- ${b}`));
  return out.join('\n') + '\n';
}
